export type Reference = { name: string; currency: string; side: string; kind: string };
export function displayValue(value: unknown, references: Record<string, Reference> = {}): string {
  if (value === null || value === undefined || value === '') return '未设置';
  if (typeof value === 'boolean') return value ? '是' : '否';
  if (Array.isArray(value))
    return value.length ? value.map((v) => displayValue(v, references)).join('、') : '无';
  const s = String(value);
  return references[s]?.name || valueLabels[s] || s;
}
